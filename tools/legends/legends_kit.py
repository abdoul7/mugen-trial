"""legends_kit.py -- bring the Legends art kit (Codex, kit v0.1) into legends.sff and legends.air.

The kit is NOT in this repo: its art stays local. Put the kit's runtime/ and data/ folders in
    source/legends-art/kit/          (ignored by git; or set LEGENDS_KIT=<folder>)
Only the three runtime atlas pages are read, using the rectangles in data/assets.json (the kit
README: "load only these three atlas pages"). The engine has no PNG atlases, so each rectangle
becomes one SFF sprite with its own palette.

Scale: the jfv motif draws all art at 2x and shows it at half size. Card faces (128x192) are
authored above display size and are used as they are (shown 64x96 in 320 space, every source
pixel kept on the 640 render). UI and VFX pieces are 1x, 320-space art, so they are doubled with
nearest-neighbour sampling to land at their authored size.

Sprite groups must match legendsmode.cpp (KIT_* constants):
  100,i card face, i = index in tools/legends/catalog.json     101,i hand thumbnail (22x22)
  120..124 hand frame: ready, armed, cooldown, blocked, empty   125,0-5 focus outline frames
  126,f family icon (f: resolve, secret arts, awakenings, plot twists)
  127,k button: square, triangle, circle, cross, L, R           128,0-2 Hype track / fill / ready
  129,0-2 squad chip: active, reserve, KO                       130,0-2 deal / relay / results panel
  131,0 card back (small)
  140 spirit shot, 141 lightning, 142 heal, 143 red aura, 144 teal aura, 145 draw spark,
  146 time ring, 147 reveal edge (frames 0..n)
"""
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
FAMILIES = ["resolve", "secret_arts", "awakenings", "plot_twists"]

UI_GROUPS = [  # (group, item, atlas name)
    (120, 0, "hand_ready"), (121, 0, "hand_armed"), (122, 0, "hand_cooldown"), (123, 0, "hand_blocked"), (124, 0, "hand_empty"),
    *[(125, k, f"focus_{k}") for k in range(6)],
    *[(126, f, f"family_{n}") for f, n in enumerate(FAMILIES)],
    *[(127, k, f"button_{n}") for k, n in enumerate(["square", "triangle", "circle", "cross", "L", "R"])],
    (128, 0, "hype_track"), (128, 1, "hype_fill"), (128, 2, "hype_ready"),
    (129, 0, "squad_active"), (129, 1, "squad_reserve"), (129, 2, "squad_ko"),
    (130, 0, "deal_panel"), (130, 1, "relay_panel"), (130, 2, "results_panel"),
    (131, 0, "card_back_small"),
]
VFX_GROUPS = [(140, "spirit_shot", 6), (141, "lightning", 4), (142, "heal", 4), (143, "aura_red", 4), (144, "aura_teal", 4),
              (145, "draw_spark", 6), (146, "time_ring", 6), (147, "reveal_edge", 6)]
# animations: action number -> (group, frames, ticks per frame, loops)
ACTIONS = {125: (125, 6, 2, True), 140: (140, 6, 2, True), 141: (141, 4, 2, True), 142: (142, 4, 4, False),
           143: (143, 4, 4, True), 145: (145, 6, 2, False)}


def kit_dir():
    d = os.environ.get("LEGENDS_KIT") or os.path.join(ROOT, "source", "legends-art", "kit")
    return d if os.path.exists(os.path.join(d, "data", "assets.json")) else None


def _crop(page, r):
    return page.crop((r["x"], r["y"], r["x"] + r["width"], r["y"] + r["height"]))


def _double(img):
    return img.resize((img.size[0] * 2, img.size[1] * 2), Image.NEAREST)


def sprites(kit, card_ids, spr):
    """spr(img, ax, ay, group, item) -> sprite (make_ui.spr). Returns (sprites, decoded 8-bit bytes)."""
    meta = json.load(open(os.path.join(kit, "data", "assets.json"), encoding="utf-8"))
    pages = {name: Image.open(os.path.join(kit, a["file"])).convert("RGBA") for name, a in meta["atlases"].items()}
    rect = {name: (atlas, r) for atlas, a in meta["atlases"].items() for name, r in a["sprites"].items()}
    out, pixels = [], 0

    def add(img, g, i):
        nonlocal pixels
        out.append(spr(img, 0, 0, g, i))
        pixels += img.size[0] * img.size[1]

    for i, cid in enumerate(card_ids):
        if cid in meta["atlases"]["cards_base"]["sprites"]:
            add(_crop(pages["cards_base"], meta["atlases"]["cards_base"]["sprites"][cid]), 100, i)  # faces: used as authored
        if f"thumb_{cid}" in rect:
            atlas, r = rect[f"thumb_{cid}"]
            add(_double(_crop(pages[atlas], r)), 101, i)
    for g, i, name in UI_GROUPS:
        atlas, r = rect[name]
        img = _crop(pages[atlas], r)
        if name in ("hype_fill", "hype_ready"):   # 1 px high strips: give them the track's inner height
            img = img.resize((img.size[0], 3), Image.NEAREST)
        add(_double(img), g, i)
    for g, base, n in VFX_GROUPS:
        for k in range(n):
            atlas, r = rect[f"{base}_{k}"]
            add(_double(_crop(pages[atlas], r)), g, k)
    return out, pixels


def air_text(kit_present):
    """legends.air: the animated pieces. Without the kit they fall back to the drawn placeholders."""
    lines = ["; generated by tools/legends/legends_kit.py"]
    fallback = {125: (11, 0), 140: (40, 0), 141: (40, 1), 142: (41, 0), 145: (41, 0)}
    for action, (g, n, t, loop) in ACTIONS.items():
        if not kit_present and action not in fallback:
            continue
        lines.append(f"[Begin Action {action}]")
        if kit_present:
            lines += [f"{g},{k}, 0,0, {t}" for k in range(n)]
            if not loop:
                lines.append(f"{g},{n - 1}, 0,0, -1")
        else:
            fg, fi = fallback[action]
            lines.append(f"{fg},{fi}, 0,0, -1")
        lines.append("")
    return "\n".join(lines) + "\n"
