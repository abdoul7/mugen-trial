"""make_legends.py -- build the Legends mode data the engine reads (patch 0010, legendsmode.cpp).

    python tools/legends/make_legends.py [assets dir]   # default build/game/assets

Writes <assets>/data/legends/:
  catalog.txt   tools/legends/catalog.json as key = value text (parsed by legendscore.cpp)
  adapters.txt  tools/legends/adapters.json, same format
  legends.sff   HUD sprites: card tiles per family, icons, rarity pips, Hype rail, echoes,
                panels (drawn here, no third-party art; 2x like the jfv motif)
The card illustrations of docs/legends-design.md section 9 are not drawn yet: tiles show the
family icon in the art window until the art kit exists.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def catalog_text(cat):
    out = ["; generated by tools/legends/make_legends.py from tools/legends/catalog.json", "[legends]",
           f"version = {cat['version']}",
           "rarity.weights = " + ",".join(str(cat["rarity_weights"][r]) for r in ("common", "rare", "epic", "legendary"))]
    h = cat["hype"]
    out += [f"hype.max = {h['max']}", f"hype.tick = {h['tick']}", f"hype.event = {h['event']}",
            f"hype.event.cap = {h['event_cap']}", f"hype.event.window = {h['event_window']}",
            f"play.cooldown = {cat['play_cooldown']}", ""]
    keys = [("revision", "revision", 1), ("family", "family", None), ("rarity", "rarity", None), ("name", "name", None),
            ("short", "short", None), ("text", "text", ""), ("effect", "effect", None), ("reservation", "reservation", 1),
            ("windup", "windup", 0), ("interruptible", "interruptible", False), ("duration", "duration", 0),
            ("per.encounter", "per_encounter", 0), ("per.fighter", "per_fighter", 0), ("flavor", "flavor", ""),
            ("needs.grounded", "needs_grounded", False),
            ("needs.control", "needs_control", False), ("hp.min", "hp_min", 0), ("hp.max", "hp_max", 1),
            ("requires", "requires", "")]
    for c in cat["cards"]:
        out.append(f"[card {c['id']}]")
        for k, src, default in keys:
            v = c.get(src, default)
            if v is None:
                raise SystemExit(f"card {c['id']}: missing {src}")
            out.append(f"{k} = {int(v) if isinstance(v, bool) else v}")
        out.append(f"enabled = {int(bool(c['enabled']))}")
        if not c["enabled"]:
            out.append(f"disabled.reason = {c['disabled_reason']}")
        if c.get("tags"):
            out.append("tags = " + ", ".join(c["tags"]))
        for k, v in c.get("params", {}).items():
            out.append(f"param.{k} = {v}")
        out.append("")
    return "\n".join(out)


def adapters_text(ad):
    out = ["; generated by tools/legends/make_legends.py from tools/legends/adapters.json"]
    for a in ad["adapters"]:
        out += [f"[adapter {a['id']}]", f"match = {a['match']}", f"custom_ai = {int(a['custom_ai'])}"]
        out += [f"tag.{t} = " + ", ".join(cmds) for t, cmds in a["tags"].items()]
        out.append("")
    return "\n".join(out)


def main():
    assets = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else os.path.join(ROOT, "build", "game", "assets")
    out = os.path.join(assets, "data", "legends")
    os.makedirs(out, exist_ok=True)
    cat = json.load(open(os.path.join(HERE, "catalog.json"), encoding="utf-8"))
    ad = json.load(open(os.path.join(HERE, "adapters.json"), encoding="utf-8"))
    open(os.path.join(out, "catalog.txt"), "w", encoding="latin-1", newline="\n").write(catalog_text(cat))
    open(os.path.join(out, "adapters.txt"), "w", encoding="latin-1", newline="\n").write(adapters_text(ad))
    if "--no-art" not in sys.argv:
        sys.path.insert(0, HERE)
        import legends_art
        n, kb, kit, kit_px = legends_art.write(os.path.join(out, "legends.sff"), [c["id"] for c in cat["cards"]])
        art = f"art kit {kit_px / 2**20:.2f} MiB decoded at 8 bits" if kit else "no art kit (placeholders only; see legends_kit.py)"
        print(f"legends: {len(cat['cards'])} cards ({sum(c['enabled'] for c in cat['cards'])} enabled), "
              f"{len(ad['adapters'])} adapters, {n} sprites ({kb} KB), {art} -> {os.path.relpath(out, ROOT)}")
    else:
        print(f"legends: catalog + adapters -> {os.path.relpath(out, ROOT)}")


if __name__ == "__main__":
    main()
